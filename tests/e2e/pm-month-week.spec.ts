import { expect, test } from "@playwright/test";
import { db } from "../../lib/db";
import { applyAnnualMonthlyPattern } from "../../modules/pm/pm-annual-service";

test.afterAll(async () => { await db.$disconnect(); });

test("edits only a dated Week, supports Week 5, and preserves overrides after regeneration", async ({ page }, testInfo) => {
  test.setTimeout(180_000);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  const user = await db.user.findUniqueOrThrow({ where: { username: "site-admin" } });
  const zone = await db.zone.findFirstOrThrow({ where: { plantId: user.plantId!, active: true } });
  const year = Number(new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Bangkok", year: "numeric" }).format(new Date())) + 1;
  const scope = { organizationId: user.organizationId!, plantId: user.plantId! };
  const plan = await db.pmAnnualPlan.create({ data: { ...scope, year, name: "Week override E2E", pmBy: "ZONE", scheduleMode: "MONTHLY_PATTERN", createdById: user.id,
    monthlyPatternVersion: 1, monthlyGeneratedVersion: 0, monthlyWeek5Rule: "NO_PM",
  } });
  for (const weekNumber of [1, 2, 3, 4]) await db.pmAnnualMonthlyWeek.create({ data: { planId: plan.id, plantId: scope.plantId, weekNumber, mode: weekNumber === 1 ? "ASSIGNMENTS" : "NO_PM" } });
  await db.pmAnnualMonthlyPattern.create({ data: { plantId: scope.plantId, planId: plan.id, weekNumber: 1, dayOfWeek: 1, displayOrder: 0, zoneId: zone.id, patternKey: `week-e2e-${Date.now()}` } });
  const actor = { id: user.id, role: "SITE_ADMIN", ...scope };
  await applyAnnualMonthlyPattern(actor, { ...scope, planId: plan.id, effectiveDateKey: `${year}-01-01` });
  const baseline = await db.pmAnnualMonthlyPattern.findMany({ where: { planId: plan.id } });
  const initial = await db.pmAnnualSchedule.findMany({ where: { planId: plan.id, slotKey: { not: null } } });
  const original = initial.find(row => row.scheduleDateKey.startsWith(`${year}-03`))!;
  await page.goto("/login");
  await page.getByPlaceholder("Username").fill("site-admin");
  await page.getByPlaceholder("Password").fill("password1234");
  await page.getByRole("button", { name: "เข้าสู่ระบบ", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboardcm/);
  const query = new URLSearchParams({ ...scope, year: String(year), planId: plan.id, month: "3", view: "month", q: "", target: zone.id, status: "SCHEDULED" });
  await page.goto(`/dashboardpm/setup?${query}`);
  const one = page.locator('[data-pm-month-week="1"]');
  await one.locator("summary").click();
  const weekday = new Date(`${original.scheduleDateKey}T12:00:00Z`).getUTCDay() || 7;
  const nextDay = weekday === 7 ? 1 : weekday + 1;
  await one.getByLabel(`วันที่ ${original.id}`, { exact: true }).selectOption(String(nextDay));
  await one.getByRole("button", { name: "บันทึกเฉพาะ Week 1", exact: true }).click();
  await expect(page).toHaveURL(/editWeek=1/);
  await expect(page.getByRole("status")).toContainText("ไม่เปลี่ยนต้นแบบ");
  expect(new URL(page.url()).searchParams.get("target")).toBe(zone.id);
  expect(new URL(page.url()).searchParams.get("status")).toBe("SCHEDULED");
  await expect(one).toHaveAttribute("open", "");
  const moved = await db.pmAnnualSchedule.findFirstOrThrow({ where: { planId: plan.id, originalScheduleId: original.id, status: "SCHEDULED" } });
  expect(moved.source).toBe("OVERRIDE");
  const fifth = page.locator('[data-pm-month-week="5"]');
  await fifth.locator("summary").click();
  const dateOptions = await fifth.getByLabel("เลือกวันที่ Week 5", { exact: true }).locator("option").allTextContents();
  expect(dateOptions.every(text => text.includes(`${year}-03-`))).toBeTruthy();
  await fifth.getByLabel("เลือกเป้าหมาย Week 5", { exact: true }).selectOption(zone.id);
  await fifth.getByRole("button", { name: "เพิ่มรายการใน Week 5", exact: true }).click();
  await fifth.getByRole("button", { name: "บันทึกเฉพาะ Week 5", exact: true }).click();
  await expect(page).toHaveURL(/editWeek=5/);
  await expect(page.getByRole("status")).toContainText("ไม่เปลี่ยนต้นแบบ");
  const custom = await db.pmAnnualSchedule.findFirstOrThrow({ where: { planId: plan.id, overrideAction: "ADD", status: "SCHEDULED" } });
  expect(Number(custom.scheduleDateKey.slice(-2))).toBeGreaterThanOrEqual(29);
  await applyAnnualMonthlyPattern(actor, { ...scope, planId: plan.id, effectiveDateKey: `${year}-01-01` });
  expect(await db.pmAnnualMonthlyPattern.findMany({ where: { planId: plan.id } })).toEqual(baseline);
  const final = await db.pmAnnualSchedule.findMany({ where: { planId: plan.id, slotKey: { not: null } } });
  expect(final.find(row => row.id === custom.id)?.status).toBe("SCHEDULED");
  expect(final.find(row => row.id === moved.id)?.status).toBe("SCHEDULED");
  expect(final.find(row => row.scheduleDateKey === original.scheduleDateKey)?.status).toBe("CANCELED");
  expect(final.filter(row => !row.scheduleDateKey.startsWith(`${year}-03`))).toEqual(initial.filter(row => !row.scheduleDateKey.startsWith(`${year}-03`)));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await expect(fifth).toHaveAttribute("open", "");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await fifth.screenshot({ path: testInfo.outputPath("week-5-mobile.png"), caret: "initial" });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.reload();
  await fifth.screenshot({ path: testInfo.outputPath("week-5-desktop.png"), caret: "initial" });
  await page.getByRole("link", { name: "เปิดเดือนนี้ใน PM Calendar", exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`month=${year}-03`));
  const calendar = page.getByRole("grid");
  await expect(calendar.locator('a[href*="scheduleId=' + moved.id + '"]').first()).toBeVisible();
  await expect(calendar.locator('a[href*="scheduleId=' + custom.id + '"]').first()).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("week-overrides-calendar.png"), fullPage: true, caret: "initial" });
  await page.goto(`/dashboardpm/setup?${query}&editWeek=5`);
  const removalWeek = page.locator('[data-pm-month-week="5"]');
  await removalWeek.getByRole("button", { name: `ลบ ${zone.name}`, exact: true }).click();
  await removalWeek.getByRole("button", { name: "บันทึกเฉพาะ Week 5", exact: true }).click();
  await expect.poll(() => db.pmAnnualSchedule.count({ where: { id: custom.id, status: "SCHEDULED" } })).toBe(0);
  await expect(removalWeek.getByRole("article")).toHaveCount(0);
  expect(await db.pmAnnualSchedule.count({ where: { planId: plan.id, scheduleDateKey: custom.scheduleDateKey, source: "OVERRIDE", status: "CANCELED", slotKey: { not: null } } })).toBe(1);
  expect(await db.pmAnnualMonthlyPattern.findMany({ where: { planId: plan.id } })).toEqual(baseline);
  expect(errors).toEqual([]);
});
