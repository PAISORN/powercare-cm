import { expect, test } from "@playwright/test";
import { tmpdir } from "node:os";
import { join } from "node:path";

test("saves website photo backgrounds and preserves them across reload and navigation", async ({ page }) => {
  test.setTimeout(180_000);
  page.setDefaultTimeout(15_000);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  await page.goto("/login");
  await page.getByPlaceholder("Username").fill("site-admin");
  await page.getByPlaceholder("Password").fill("password1234");
  await page.getByRole("button", { name: "เข้าสู่ระบบ", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboardcm/);
  await page.goto("/settings");
  await expect(page).toHaveURL(/\/settings$/);
  await expect(page.getByRole("heading", { name: "การตั้งค่าส่วนบุคคล", exact: true })).toBeVisible();
  await page.getByRole("radio", { name: /^สว่าง/ }).check();
  const maintenance = page.getByRole("radio", { name: /ช่างซ่อมบำรุง/ });
  const campus = page.getByRole("radio", { name: /โรงงานอุตสาหกรรม/ });
  await maintenance.check();
  await expect(page.getByRole("slider", { name: "ความเบลอของภาพพื้นหลัง" })).toHaveValue("0");
  await page.getByRole("button", { name: "บันทึกการตั้งค่า", exact: true }).click();
  await expect(page.locator("html")).toHaveAttribute("data-background", "image-maintenance");
  await expect(page.getByRole("status").filter({ hasText: "บันทึกการตั้งค่าเรียบร้อยแล้ว" })).toBeVisible();
  await page.reload();
  await expect(maintenance).toBeChecked();
  expect(await page.evaluate(() => getComputedStyle(document.body, "::before").backgroundImage)).toContain("powercare-maintenance-hero.webp");
  const asset = await page.request.get("/landing/powercare-maintenance-hero.webp");
  expect(asset.ok()).toBe(true);
  expect(asset.headers()["content-type"]).toContain("image/webp");
  await page.setViewportSize({ width: 1440, height: 1000 });
  await maintenance.locator("xpath=../../..").screenshot({ path: join(tmpdir(), "powercare-settings-backgrounds-desktop.png"), caret: "initial" });
  await campus.check();
  await page.getByRole("radio", { name: /^กลางคืน/ }).check();
  const blur = page.getByRole("slider", { name: "ความเบลอของภาพพื้นหลัง" });
  await blur.press("Home");
  for (let step = 0; step < 4; step++) await blur.press("ArrowRight");
  const brightness = page.getByRole("slider", { name: "ความสว่างของภาพพื้นหลัง" });
  await brightness.press("Home");
  for (let step = 0; step < 33; step++) await brightness.press("ArrowRight");
  await page.getByRole("button", { name: "บันทึกการตั้งค่า", exact: true }).click();
  await expect(page.locator("html")).toHaveAttribute("data-background", "image-industrial-campus");
  await page.goto("/dashboardcm");
  await expect(page.locator("html")).toHaveAttribute("data-background", "image-industrial-campus");
  expect(await page.evaluate(() => getComputedStyle(document.body, "::before").backgroundImage)).toContain("powercare-industrial-campus.webp");
  await page.screenshot({ path: join(tmpdir(), "powercare-settings-applied-desktop.png"), caret: "initial" });
  await page.goto("/settings");
  await expect(campus).toBeChecked();
  await expect(page.getByRole("slider", { name: "ความเบลอของภาพพื้นหลัง" })).toHaveValue("4");
  await expect(page.getByRole("slider", { name: "ความสว่างของภาพพื้นหลัง" })).toHaveValue("78");
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator(".app-workspace")).toHaveCSS("margin-left", "0px");
  await campus.locator("xpath=../..").screenshot({ path: join(tmpdir(), "powercare-settings-background-mobile.png"), caret: "initial" });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  console.log(`Settings screenshots: ${join(tmpdir(), "powercare-settings-backgrounds-desktop.png")} | ${join(tmpdir(), "powercare-settings-background-mobile.png")}`);
  await page.getByRole("button", { name: "คืนค่าเริ่มต้น", exact: true }).click();
  await page.getByRole("button", { name: "บันทึกการตั้งค่า", exact: true }).click();
  await expect(page.locator("html")).toHaveAttribute("data-background", "image-maintenance");
  await page.reload();
  await expect(page.locator("html")).toHaveAttribute("data-background", "image-maintenance");
  expect(errors).toEqual([]);
});
