import { expect, test } from "@playwright/test";
import { db } from "../../lib/db";
import { nthWeekdayOfMonth } from "../../modules/pm/pm-annual-types";

test.afterAll(async () => { await db.$disconnect(); });

test("saves and generates an independent Week 5 Pattern from its card", async ({ page }, testInfo) => {
  test.setTimeout(180_000);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  // A separate year keeps this fixture independent of the legacy Monthly Pattern test.
  const year = Number(new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Bangkok", year: "numeric" }).format(new Date())) + 2;
  await page.goto("/login");
  await page.getByPlaceholder("Username").fill("site-admin");
  await page.getByPlaceholder("Password").fill("password1234");
  await page.getByRole("button", { name: "เข้าสู่ระบบ", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboardcm/);
  await page.goto(`/dashboardpm/setup?year=${year}`);
  await page.locator('input[name="name"]').fill("Explicit Week 5 E2E");
  await page.locator('select[name="pmBy"]').selectOption("ZONE");
  await page.locator('select[name="scheduleMode"]').selectOption("MONTHLY_PATTERN");
  await page.getByRole("button", { name: "สร้าง Draft", exact: true }).click();
  const five = page.getByRole("region", { name: "Pattern Week 5", exact: true });
  await expect(five).toBeVisible();
  await five.getByRole("button", { name: "รายการ Week 5", exact: true }).click();
  for (const number of [1, 2, 3, 4]) await page.getByRole("region", { name: `Pattern Week ${number}`, exact: true }).getByRole("button", { name: "No PM", exact: true }).click();
  await five.getByRole("button", { name: "เพิ่ม PM ใน Week 5", exact: true }).click();
  await five.getByRole("group", { name: "เลือก PM Pattern Week 5" }).getByRole("checkbox").first().check();
  await five.getByRole("button", { name: "เพิ่ม 1 รายการใน Week 5", exact: true }).click();
  await page.setViewportSize({ width: 1600, height: 1000 });
  await five.screenshot({ path: testInfo.outputPath("pattern-week-five-desktop.png"), caret: "initial" });
  await page.getByRole("button", { name: "Save Monthly Pattern", exact: true }).click();
  await expect(page).toHaveURL(/saved=monthly-pattern(?:&|$)/);
  const planId = new URL(page.url()).searchParams.get("planId")!;
  const saved = await db.pmAnnualMonthlyPattern.findMany({ where: { planId } });
  expect(saved).toHaveLength(1);
  expect(saved[0]).toMatchObject({ weekNumber: 5, dayOfWeek: 1 });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await five.getByRole("button", { name: "รายการ Week 5", exact: true }).click();
  await expect(five.getByRole("button", { name: "รายการ Week 5", exact: true })).toHaveAttribute("aria-expanded", "true");
  await expect(five.getByRole("article")).toHaveCount(1);
  await five.getByRole("button", { name: "เพิ่ม PM ใน Week 5", exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await five.screenshot({ path: testInfo.outputPath("pattern-week-five-mobile.png"), caret: "initial" });
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.getByLabel("Effective Start Date").fill(`${year}-01-01`);
  await page.getByRole("button", { name: "Preview Annual Plan", exact: true }).click();
  await expect(page.getByText("Diff Preview")).toBeVisible();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Confirm Generate", exact: true }).click();
  await expect(page.getByText("In Sync", { exact: true })).toBeVisible();
  const schedules = await db.pmAnnualSchedule.findMany({ where: { planId, status: "SCHEDULED", slotKey: { not: null } } });
  const expected = Array.from({ length: 12 }, (_, month) => nthWeekdayOfMonth(year, month + 1, 1, 5)).filter(Boolean);
  expect(schedules.map(row => row.scheduleDateKey).sort()).toEqual(expected.sort());
  expect(schedules.every(row => row.zoneId === saved[0].zoneId)).toBe(true);
  const plan = await db.pmAnnualPlan.findUniqueOrThrow({ where: { id: planId } });
  const entry = schedules[0];
  await page.goto(`/dashboardpm/calendar?organizationId=${plan.organizationId}&plantId=${plan.plantId}&month=${entry.scheduleDateKey.slice(0, 7)}&date=${entry.scheduleDateKey}`);
  await expect(page.locator(`a[href*="scheduleId=${entry.id}"]`).first()).toBeVisible();
  expect(errors).toEqual([]);
});
